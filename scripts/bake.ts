// Renders Momo's 3D model into the terminal sprites (hooks/sprites.generated.ts) and the README images (assets/).
// Run from the repository root: bun scripts/bake.ts

import { mkdirSync, writeFileSync } from 'node:fs'

import type { Emotion } from '../types'
import { GESTURES, render, RIG } from './momo3d'
import type { Pose, RGBA } from './momo3d'
import { apng, png } from './png'
import type { Image } from './png'

const EMOTIONS: Emotion[] = ['happy', 'proud', 'calm', 'curious', 'worried', 'angry', 'sleepy']
const POSES: Pose[] = ['sit', 'jump', 'squash']
// Emotions whose eyes are open, so they get a blinking sprite too.
const BLINKERS = new Set<Emotion>(['calm', 'curious', 'worried', 'angry'])

const SPRITE = { width: 44, height: 32 }
const VIEW = { span: 3.25, bottom: -1.05 }
const DARK: [number, number, number] = [29, 34, 48]

const at = (scale: number, samples: number) => ({
  width: SPRITE.width * scale,
  height: SPRITE.height * scale,
  samples,
  ...VIEW,
})

/** A small sprite for the terminal: hard edges (a cell is either Momo or not) and a darker rim so he shows on any background. */
function terminalSprite(emotion: Emotion, pose: Pose, isBlinking: boolean): (number[] | null)[][] {
  // One sample per pixel keeps the eyes and brows crisp at this size.
  const image = render(emotion, pose, isBlinking, at(1, 1))
  const isSolid = (x: number, y: number) => (image[y]?.[x]?.[3] ?? 0) >= 110
  return image.map((row, y) =>
    row.map(([r, g, b], x) => {
      if (!isSolid(x, y)) return null
      const isEdge = !isSolid(x - 1, y) || !isSolid(x + 1, y) || !isSolid(x, y - 1) || !isSolid(x, y + 1)
      const k = isEdge ? 0.72 : 1
      return [Math.round(r * k), Math.round(g * k), Math.round(b * k)]
    }),
  )
}

/** Up to 255 colors: the most common ones, each other color mapped to its nearest. */
function quantize(sprites: (number[] | null)[][][]) {
  const buckets = new Map<number, { sum: number[]; count: number }>()
  for (const sprite of sprites) {
    for (const row of sprite) {
      for (const color of row) {
        if (color === null) continue
        const key = ((color[0]! >> 3) << 10) | ((color[1]! >> 3) << 5) | (color[2]! >> 3)
        const bucket = buckets.get(key) ?? { sum: [0, 0, 0], count: 0 }
        bucket.sum = bucket.sum.map((s, i) => s + color[i]!)
        bucket.count += 1
        buckets.set(key, bucket)
      }
    }
  }
  const palette = [...buckets.values()]
    .sort((a, b) => b.count - a.count)
    .slice(0, 255)
    .map(({ sum, count }) => sum.map(s => Math.round(s / count)))
  const nearest = (color: number[]) => {
    let best = 0
    let bestDistance = Infinity
    palette.forEach((entry, index) => {
      const distance = (entry[0]! - color[0]!) ** 2 + (entry[1]! - color[1]!) ** 2 + (entry[2]! - color[2]!) ** 2
      if (distance < bestDistance) {
        bestDistance = distance
        best = index
      }
    })
    return best + 1
  }
  return { palette, nearest }
}

function bakeSprites() {
  const entries: { key: string; sprite: (number[] | null)[][] }[] = []
  for (const emotion of EMOTIONS) {
    for (const pose of POSES) {
      entries.push({ key: `${emotion}:${pose}:0`, sprite: terminalSprite(emotion, pose, false) })
      if (BLINKERS.has(emotion)) {
        entries.push({ key: `${emotion}:${pose}:1`, sprite: terminalSprite(emotion, pose, true) })
      }
    }
  }
  const { palette, nearest } = quantize(entries.map(entry => entry.sprite))
  const lines = entries.map(({ key, sprite }) => {
    const bytes = Buffer.from(sprite.flatMap(row => row.map(color => (color === null ? 0 : nearest(color)))))
    return `  '${key}': '${bytes.toString('base64')}',`
  })
  const hexes = palette.map(([r, g, b]) => `0x${((r! << 16) | (g! << 8) | b!).toString(16).padStart(6, '0')}`)

  writeFileSync(
    'hooks/sprites.generated.ts',
    [
      '// Generated by scripts/bake.ts from the 3D model in scripts/momo3d.ts. Do not edit; run `bun scripts/bake.ts`.',
      '// Each sprite is base64 of one byte per pixel, row by row: 0 is see-through, n is PALETTE[n - 1].',
      '',
      `export const WIDTH = ${SPRITE.width}`,
      `export const HEIGHT = ${SPRITE.height}`,
      '',
      'export const PALETTE: readonly number[] = [',
      ...chunked(hexes, 10).map(group => `  ${group.join(', ')},`),
      ']',
      '',
      'export const SPRITES: Readonly<Record<string, string>> = {',
      ...lines,
      '}',
      '',
    ].join('\n'),
  )
  console.log(`sprites: ${entries.length}, colors: ${palette.length}`)
}

const chunked = <T>(items: T[], size: number): T[][] =>
  Array.from({ length: Math.ceil(items.length / size) }, (_, i) => items.slice(i * size, i * size + size))

const toImage = (rows: RGBA[][]): Image => rows.map(row => row.map(pixel => [...pixel]))

/** Places images side by side with a gap, on transparency. */
function row(images: Image[], gap: number): Image {
  const height = Math.max(...images.map(image => image.length))
  return Array.from({ length: height }, (_, y) =>
    images.flatMap((image, index) => [
      ...(image[y] ?? []),
      ...(index < images.length - 1 ? Array.from({ length: gap }, () => [0, 0, 0, 0]) : []),
    ]),
  )
}

/** Nearest-neighbour enlargement, so the terminal preview shows real pixels. */
const enlarge = (image: Image, k: number): Image =>
  image.flatMap(line => Array.from({ length: k }, () => line.flatMap(pixel => Array.from({ length: k }, () => pixel))))

async function bakeImages() {
  mkdirSync('assets', { recursive: true })

  writeFileSync('assets/momo.png', png(toImage(render('calm', 'sit', false, at(11, 3)))))
  console.log('assets/momo.png')

  writeFileSync('assets/momo-moods.png', png(row(EMOTIONS.map(e => toImage(render(e, 'sit', false, at(5, 2)))), 12)))
  console.log('assets/momo-moods.png')

  const terminal = EMOTIONS.map(e => terminalSprite(e, 'sit', false).map(line => line.map(c => (c === null ? [0, 0, 0, 0] : [...c, 255]))))
  writeFileSync('assets/momo-terminal.png', png(enlarge(row(terminal, 3), 5), DARK))
  console.log('assets/momo-terminal.png')

  // Momo Desktop: his body per mood, pose and blink, plus one ear and the tail, which the app swings
  // live around the pivots in rig.js; and the menu-bar icon. All 220x160, in the same frame.
  mkdirSync('desktop/sprites', { recursive: true })
  const desktop = at(5, 2)
  for (const emotion of EMOTIONS) {
    for (const pose of POSES) {
      for (const blink of BLINKERS.has(emotion) ? [false, true] : [false]) {
        const image = render(emotion, pose, blink, { ...desktop, layer: 'body' })
        writeFileSync(`desktop/sprites/${emotion}-${pose}-${blink ? 1 : 0}.png`, png(toImage(image)))
      }
    }
  }
  // Hand gestures (covering his eyes, waving, clapping, thinking), sitting, for every mood.
  for (const emotion of EMOTIONS) {
    for (const gesture of GESTURES) {
      const image = render(emotion, 'sit', false, { ...desktop, layer: 'body', gesture })
      writeFileSync(`desktop/sprites/${emotion}-g-${gesture}.png`, png(toImage(image)))
    }
  }
  writeFileSync('desktop/sprites/ear.png', png(toImage(render('calm', 'sit', false, { ...desktop, layer: 'ear' }))))
  writeFileSync('desktop/sprites/tail.png', png(toImage(render('calm', 'sit', false, { ...desktop, layer: 'tail' }))))
  const toPixels = ([x, y]: [number, number]) => [
    Math.round(((x + desktop.span / 2) * desktop.width) / desktop.span),
    Math.round(desktop.height - ((y - desktop.bottom) * desktop.width) / desktop.span),
  ]
  writeFileSync(
    'desktop/rig.js',
    [
      '// Generated by scripts/bake.ts: where the ear and tail sprites attach, in sprite pixels.',
      `window.MOMO_RIG = ${JSON.stringify({ size: [desktop.width, desktop.height], ear: toPixels(RIG.earPivot), tail: toPixels(RIG.tailPivot) })}`,
      '',
    ].join('\n'),
  )
  writeFileSync('desktop/sprites/tray.png', png(toImage(render('calm', 'sit', false, at(1, 3)))))
  console.log('desktop/sprites')

  // The hop demo: the plugin's own animation code, drawn with the smooth 3D renders.
  const { initialActor, poseOf, step } = await import('../hooks/stage')
  const scale = 3
  const stage = { columns: 72, rows: 22 }
  const script: Emotion[] = [
    ...Array<Emotion>(45).fill('happy'),
    ...Array<Emotion>(15).fill('curious'),
    ...Array<Emotion>(18).fill('worried'),
    ...Array<Emotion>(18).fill('angry'),
    ...Array<Emotion>(32).fill('proud'),
  ]
  let seed = 11
  const random = () => (seed = (seed * 16807) % 2147483647) / 2147483647
  const renders = new Map<string, Image>()
  const big = (emotion: Emotion, pose: Pose, blink: boolean) => {
    const key = `${emotion}:${pose}:${blink}`
    if (!renders.has(key)) renders.set(key, toImage(render(emotion, pose, blink, at(scale, 2))))
    return renders.get(key) as Image
  }
  let actor = initialActor()
  const width = stage.columns * scale
  const height = stage.rows * 2 * scale
  const frames: Image[] = script.map(emotion => {
    actor = step(actor, emotion, stage, random)
    const frame: Image = Array.from({ length: height }, () => Array.from({ length: width }, () => [...DARK, 255]))
    const left = Math.round(actor.x * scale)
    const top = height - SPRITE.height * scale - Math.round(actor.y * scale)
    // A soft shadow that shrinks as Momo rises.
    const shadowWidth = (SPRITE.width * scale * 0.42) / (1 + actor.y / 20)
    const shadowX = left + (SPRITE.width * scale) / 2
    for (let y = height - 10; y < height; y += 1) {
      for (let x = Math.floor(shadowX - shadowWidth); x <= shadowX + shadowWidth; x += 1) {
        const d = ((x - shadowX) / shadowWidth) ** 2 + ((y - (height - 5)) / 5) ** 2
        const pixel = frame[y]?.[x]
        if (pixel && d < 1) pixel.splice(0, 3, ...pixel.slice(0, 3).map(v => Math.round(v * (0.55 + 0.45 * d))))
      }
    }
    const sprite = big(emotion, poseOf(actor), actor.blinkTicks < 3 && BLINKERS.has(emotion))
    sprite.forEach((line, sy) =>
      line.forEach(([r = 0, g = 0, b = 0, a = 0], sx) => {
        const x = actor.isFacingLeft ? left + line.length - 1 - sx : left + sx
        const pixel = frame[top + sy]?.[x]
        if (!pixel || a === 0) return
        const t = a / 255
        pixel.splice(0, 3, Math.round(r * t + pixel[0]! * (1 - t)), Math.round(g * t + pixel[1]! * (1 - t)), Math.round(b * t + pixel[2]! * (1 - t)))
      }),
    )
    return frame
  })
  writeFileSync('assets/momo-demo.png', apng(frames, null, 70))
  console.log(`assets/momo-demo.png (${frames.length} frames)`)
}

bakeSprites()
await bakeImages()
